<script lang="ts">
	import { resolve } from '$app/paths';
	import { goto } from '$app/navigation';
	import { authStore } from '$lib/auth.svelte';
	import { profileStore, type SetupPath } from '$lib/profile.svelte';
	import { getNessieSample, type NessieSampleResult } from '$lib/api';
	import type { NessieSampleResponse } from '$lib/types';

	type Step = 1 | 2 | 3;

	const STEPS: { id: Step; label: string }[] = [
		{ id: 1, label: 'Welcome' },
		{ id: 2, label: 'Setup path' },
		{ id: 3, label: 'Review' }
	];

	interface PathOption {
		id: SetupPath;
		title: string;
		body: string;
		available: boolean;
		badge: string | null;
	}

	const pathOptions: PathOption[] = [
		{
			id: 'sample',
			title: 'Sample workspace',
			body: 'Explore Ginseng with a simulated banking profile — accounts, deposits, and bills generated by our demo data provider. Clearly labeled as sample data everywhere.',
			available: true,
			badge: null
		},
		{
			id: 'import',
			title: 'Import a bank CSV',
			body: 'Upload transaction history exported from your bank and classify it with Ginseng\u2019s help.',
			available: false,
			badge: 'Next update'
		},
		{
			id: 'manual',
			title: 'Enter manually',
			body: 'Type in your accounts, income, and bills by hand. Nothing leaves your workspace.',
			available: false,
			badge: 'Next update'
		}
	];

	// Resume where the user left off; `profileStore` drives persistence.
	let step = $state<Step>(1);
	let selectedPath = $state<SetupPath | null>(null);
	let sample = $state<NessieSampleResult | null>(null);
	let sampleLoading = $state(false);
	let consented = $state(false);
	let finishing = $state(false);
	let saveError = $state('');
	let resumed = $state(false);

	const profileReady = $derived(
		profileStore.status === 'loaded' || profileStore.status === 'missing' || profileStore.status === 'bypassed'
	);

	const canAdvanceFromWelcome = $derived(profileReady);
	const canAdvanceFromPath = $derived(selectedPath !== null);
	// The sample preview is a courtesy, not a prerequisite: the cash
	// model runs without the demo provider, so a provider outage must
	// not trap the user in onboarding. Consent is required only when
	// there is actually sample data to consent to.
	const sampleUnavailable = $derived(sample !== null && sample.status !== 'ok');
	const canFinish = $derived(
		selectedPath === 'sample' && !finishing && (sampleUnavailable || consented)
	);

	// One-time restore from the persisted profile.
	$effect(() => {
		if (resumed || !profileStore.profile) return;
		resumed = true;
		step = Math.min(3, Math.max(1, profileStore.profile.onboarding_step)) as Step;
		selectedPath = profileStore.profile.setup_path;
	});

	// Fetch the preview whenever the review step is the active one —
	// including a resumed session that lands directly on step 3, which
	// never passes through `advance()`.
	$effect(() => {
		if (step === 3 && selectedPath === 'sample' && sample === null && !sampleLoading) {
			void loadSample();
		}
	});

	async function advance(from: Step) {
		if (from === 1 && !canAdvanceFromWelcome) return;
		if (from === 2 && !canAdvanceFromPath) return;

		saveError = '';
		const next = (from + 1) as Step;
		const saved = await profileStore.updateStep(next);
		if (!saved) {
			saveError = profileStore.loadError ?? 'Could not save your progress.';
			return;
		}
		step = next;

	}

	async function loadSample() {
		if (sample || sampleLoading) return;
		sampleLoading = true;
		sample = await getNessieSample();
		sampleLoading = false;
	}

	async function choosePath(path: SetupPath) {
		selectedPath = path;
		saveError = '';
		if (path !== 'sample') consented = false;
		const saved = await profileStore.setSetupPath(path);
		if (!saved) saveError = profileStore.loadError ?? 'Could not save your choice.';
	}

	async function finish() {
		if (!canFinish) return;
		finishing = true;
		saveError = '';
		const saved = await profileStore.completeSetup('sample');
		if (!saved) {
			saveError = profileStore.loadError ?? 'Could not save your setup.';
			finishing = false;
			return;
		}
		goto(resolve('/'), { replaceState: true });
	}

	async function back() {
		saveError = '';
		const prev = (step - 1) as Step;
		await profileStore.updateStep(prev);
		step = prev;
	}

	function money(amount: number): string {
		return amount.toLocaleString('en-US', { style: 'currency', currency: 'USD', maximumFractionDigits: 2 });
	}

	function sampleData(): NessieSampleResponse | null {
		return sample?.status === 'ok' ? sample.data : null;
	}
</script>

