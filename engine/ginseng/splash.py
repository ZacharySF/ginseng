_ROWS = braille.normalize(ART)
WIDTH = max(map(len, _ROWS))
HEIGHT = len(_ROWS)

# One digit (0-8) per ART character: how many of its 8 braille sub-dots are
# lit. Rows line up with _ROWS one-for-one -- SHADE was never run through
# `braille.normalize`, so it only stays aligned as long as ART itself needs
# no left-trim (true today: WIDTH == 78, the raw row width).
_SHADE_ROWS = SHADE.splitlines() if WIDTH == 78 else None


def render_splash(width: int = WIDTH) -> str:
    """Plain text (not a Rich Text object) so the caller can style it with
    Textual markup -- e.g. a `$g-*` coord role -- and have it recolor on
    every coord switch."""
    return "\n".join(braille.scale(_ROWS, width))


def shade_rows(width: int = WIDTH) -> list[str] | None:
    """Per-character dot-density ('0'-'8'), aligned to `render_splash`'s
    output -- but only at native width: `braille.scale` resamples dot bits
    into brand new characters when downscaling, which this digit grid can't
    follow, so callers must fall back to a flat color below native width."""
    if width != WIDTH:
        return None
    return _SHADE_ROWS
