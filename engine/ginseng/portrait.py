WIDTH = max(map(len, _ROWS))
HEIGHT = len(_ROWS)


def render_portrait(width: int = WIDTH) -> str:
    """Fit the Braille dot matrix to `width` cells without wrapping or cropping."""
    rows = braille.scale(_ROWS, width)
    return "\n".join(rows)
